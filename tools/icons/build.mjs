// Builds Fume's icon set: filled Lucide plus Fume's own icons.
// In:  tools/icons/icons.mjs (the drawing of every icon, on Lucide's 24 px grid)
// Out: design-system/icons/svg/<name>.svg   one file per icon, currentColor, 24 px
//      design-system/icons/sprite.svg       every icon as <symbol id="fi-<name>">, for <use href="#fi-<name>">
//      design-system/icons/icons.json       manifest: name, Lucide source, kind, status, note
// Usage: node tools/icons/build.mjs
//
// How a Lucide icon becomes a filled Fume icon (see design-system/icons/README.md):
//   fill  closed Lucide shapes are filled, with a 2 px round-joined stroke in the same colour, so the
//         outline keeps Lucide's exact footprint and soft corners
//   cut   inner details are knocked out of the fill (a mask), so the icon stays one colour
//   line  icons that are only lines (check, plus, x, arrows) stay lines, at the heavier LINE width,
//         so they carry the same weight as the filled ones
//   solid exact filled geometry with no stroke (dots, Fume's own shapes)
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ICONS, LINE, CUT, DEFAULT_STATUS } from "./icons.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "design-system/icons");
const svgDir = join(out, "svg");

const paint = {
  fill: () => 'fill="currentColor" stroke="currentColor" stroke-width="2" stroke-linejoin="round"',
  solid: () => 'fill="currentColor"',
  line: (o) => `fill="none" stroke="currentColor" stroke-width="${o.w ?? LINE}" stroke-linecap="round" stroke-linejoin="round"`,
  cut: () => 'fill="#000"',
  cutline: (o) => `fill="none" stroke="#000" stroke-width="${o.w ?? CUT}" stroke-linecap="round" stroke-linejoin="round"`,
};

function el([role, tag, attrs, opts = {}]) {
  if (!paint[role]) throw new Error(`unknown role ${role}`);
  return `<${tag} ${attrs} ${paint[role](opts)}/>`;
}

function parts(name, icon, idPrefix) {
  const defs = [];
  const body = (icon.body || []).map(el).join("");
  const top = (icon.top || []).map(el).join("");
  let inner = body;
  if (icon.cuts?.length) {
    const id = `${idPrefix}${name}-cut`;
    defs.push(`<mask id="${id}" maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24"><rect width="24" height="24" fill="#fff"/>${icon.cuts.map(el).join("")}</mask>`);
    inner = `<g mask="url(#${id})">${body}</g>`;
  }
  return { defs: defs.join(""), inner: inner + top };
}

mkdirSync(svgDir, { recursive: true });
for (const f of readdirSync(svgDir)) if (f.endsWith(".svg")) rmSync(join(svgDir, f));

const symbols = [];
const sharedDefs = [];
const manifest = [];
for (const [name, icon] of Object.entries(ICONS)) {
  const one = parts(name, icon, "");
  const file = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">` +
    (one.defs ? `<defs>${one.defs}</defs>` : "") + one.inner + `</svg>\n`;
  writeFileSync(join(svgDir, `${name}.svg`), file);

  const sp = parts(name, icon, "fi-");
  if (sp.defs) sharedDefs.push(sp.defs);
  symbols.push(`<symbol id="fi-${name}" viewBox="0 0 24 24">${sp.inner}</symbol>`);
  manifest.push({ name, lucide: icon.from || null, kind: icon.kind, status: icon.status || DEFAULT_STATUS, note: icon.note || "" });
}

writeFileSync(join(out, "sprite.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">` +
  `<defs>${sharedDefs.join("")}</defs>\n${symbols.join("\n")}\n</svg>\n`);
writeFileSync(join(out, "icons.json"), JSON.stringify({
  $description: "Fume icons. Generated by node tools/icons/build.mjs from tools/icons/icons.mjs; do not edit by hand.",
  grid: 24, line: LINE, cut: CUT, icons: manifest,
}, null, 2) + "\n");
console.log(`icons: ${manifest.length} built -> design-system/icons/`);
