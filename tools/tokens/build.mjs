// Builds the UI token layer.
// In:  tokens/fume-tokens.json (brand primitives, approved v1.3)
//      design-system/tokens/ui.tokens.json (semantic UI tokens)
//      design-system/tokens/components/*.tokens.json (component tokens, merged in)
// Out: design-system/tokens/ui.css            CSS custom properties (--ui-*), pointing at --fume-* primitives
//      design-system/tokens/ui.resolved.json  every token with its final literal value, for agents and the MCP server
// Usage: node tools/tokens/build.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const prim = JSON.parse(readFileSync(join(root, "tokens/fume-tokens.json"), "utf8"));
const ui = JSON.parse(readFileSync(join(root, "design-system/tokens/ui.tokens.json"), "utf8"));
// Component tokens: one file per component family in design-system/tokens/components/*.tokens.json, each with
// its own top-level groups (field, check, switch, ...). Merged into the same --ui-* layer; a group name may
// exist only once across all files.
const compDir = join(root, "design-system/tokens/components");
if (existsSync(compDir)) {
  for (const f of readdirSync(compDir).filter((f) => f.endsWith(".tokens.json")).sort()) {
    const part = JSON.parse(readFileSync(join(compDir, f), "utf8"));
    for (const [k, v] of Object.entries(part)) {
      if (k.startsWith("$")) continue;
      if (k in ui) { console.error(`Token group "${k}" in components/${f} already exists`); process.exit(1); }
      ui[k] = v;
    }
  }
}

const primitives = {};
for (const group of ["color", "font", "type", "radius", "space"]) {
  for (const [k, v] of Object.entries(prim[group] || {})) primitives[k] = v.value;
}

// Flatten ui tokens: color.action.primary -> action-primary, glass.filter -> glass-filter
const flat = {};
(function walk(node, path) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "value" in v) {
      const parts = [...path, k];
      const name = (parts[0] === "color" ? parts.slice(1) : parts).join("-");
      flat[parts.join(".")] = { name, ...v };
    } else if (v && typeof v === "object") walk(v, [...path, k]);
  }
})(ui, []);

const byPath = flat;
const hexToRgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const missing = [];
const primLiteral = (name) => {
  if (!(name in primitives)) { missing.push(name); return "MISSING"; }
  return primitives[name];
};

function toCss(value) {
  return value
    .replace(/alpha\(\{fume\.([\w-]+)\},\s*([\d.]+)\)/g, (_, n, a) => `rgb(${hexToRgb(primLiteral(n)).join(" ")} / ${a})`)
    .replace(/\{fume\.([\w-]+)\}/g, (_, n) => { primLiteral(n); return `var(--fume-${n})`; })
    .replace(/\{([\w.-]+)\}/g, (_, p) => (byPath[p] ? `var(--ui-${byPath[p].name})` : (missing.push(p), "MISSING")));
}
function toLiteral(value, depth = 0) {
  if (depth > 5) throw new Error("reference loop in " + value);
  return value
    .replace(/alpha\(\{fume\.([\w-]+)\},\s*([\d.]+)\)/g, (_, n, a) => `rgb(${hexToRgb(primLiteral(n)).join(" ")} / ${a})`)
    .replace(/\{fume\.([\w-]+)\}/g, (_, n) => primLiteral(n))
    .replace(/\{([\w.-]+)\}/g, (_, p) => (byPath[p] ? toLiteral(byPath[p].value, depth + 1) : "MISSING"));
}

const lines = [
  "/* GENERATED by tools/tokens/build.mjs from design-system/tokens/ui.tokens.json and tokens/components/*.tokens.json. Do not edit by hand. */",
  "/* Fume UI tokens, " + (ui.$status || "") + ". Load tokens/fume-tokens.css first. */",
  ":root {",
];
const resolved = {};
for (const [path, t] of Object.entries(flat)) {
  lines.push(`  --ui-${t.name}: ${toCss(t.value)};${t.description ? ` /* ${t.description.replace(/\*\//g, "")} */` : ""}`);
  resolved[path] = { css: `var(--ui-${t.name})`, value: toLiteral(t.value), ...(t.description && { description: t.description }), ...(t.status && { status: t.status }) };
}
lines.push("}", "");

// Open choices ($options): each candidate resolved to the CSS variable it would set and its literal value.
const options = {};
for (const [group, cands] of Object.entries(ui.$options || {})) {
  if (group.startsWith("$")) continue;
  options[group] = {};
  for (const [id, c] of Object.entries(cands)) {
    const tokens = {};
    for (const [path, value] of Object.entries(c.tokens)) {
      if (!byPath[path]) { missing.push(path); continue; }
      tokens[path] = { css: `--ui-${byPath[path].name}`, value: toLiteral(value) };
    }
    options[group][id] = { name: c.name, note: c.note, tokens };
  }
}

if (missing.length) { console.error("Unresolved references:", [...new Set(missing)].join(", ")); process.exit(1); }
writeFileSync(join(root, "design-system/tokens/ui.css"), lines.join("\n"));
writeFileSync(join(root, "design-system/tokens/ui.resolved.json"),
  JSON.stringify({ $description: "Generated. Every Fume UI token with its CSS variable and final value.", $principles: ui.$principles, tokens: resolved, ...(Object.keys(options).length && { options }) }, null, 2) + "\n");
console.log(`ui tokens: ${Object.keys(flat).length} written`);
