const day = 864e5;

const ago = (days: number) => new Date(Date.parse("2026-10-15T12:00:00Z") - days * day).toISOString();

const approved = (evidence?: string, days = 9): Provenance => ({
  origin: "customer",
  state: "approved",
  by: "u-maja",
  at: ago(days),
  ...(evidence ? { evidence } : {}),
});

const proposed = (evidence: string, confidence: Provenance["confidence"] = "medium"): Provenance => ({
  origin: "engine",
  state: "proposed",
  evidence,
  confidence,
});

const c = (name: string, hex: string, pantone?: string): ColourValue => ({
  name,
  hex,
  ...(pantone ? { pantone } : {}),
});

const blend = (...rows: [string, number][]): FibreBlend => ({ fibres: rows.map(([fibre, pct]) => ({ fibre, pct })) });

const parts = (...rows: SpecPart[]): PartsValue => ({ parts: rows });

/** What a product holds beyond its facts: its kind, specs, parts, reference shots and files. */
export interface ProductSpecs {
  kindId: string;
  specs: SpecEntry[];
  parts: ProductPart[];
  shots: ReferenceShot[];
  files?: ProductFile[];
}

